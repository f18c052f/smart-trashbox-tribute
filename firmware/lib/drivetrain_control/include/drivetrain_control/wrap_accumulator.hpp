#pragma once

// drivetrain_control WrapAccumulator (design.md L4 "WrapAccumulator", 要件
// 4.4, 4.5, 7.1, 7.2, 7.3, 7.4).
//
// ハードウェアカウンタ（例: PCNT の符号付き16bit カウンタ、法 65536）は、
// 一定範囲を超えて回転すると必ず折り返す。この折り返しを検出して桁上げし、
// 「連続した」64bit の累積カウントへ変換するのが本クラスの責務である
// （要件 7.1, 7.3）。ポート契約（EncoderPort::read()）が返す値は折り返しを
// 含まない累積カウントであり、その換算は本クラスがアダプタへ提供する
// 純ロジックとして持つ（要件 7.5、ports.hpp 参照）。実機を用いずホスト上で
// テストできる（要件 7.2）。
//
// アルゴリズム: 前回の生値 last_raw との差 delta = raw_now - last_raw を、
// 法 modulus で "最短経路" へ折り返す。すなわち delta を
// [0, modulus) へ正規化したあと、modulus/2 を超える側は modulus を引いて
// (-modulus/2, +modulus/2] の範囲へ写像し、その値を積算する。これにより
// 「大きな負の生値差（実際は正転で折り返した）」と「大きな正の生値差
// （実際は逆転で折り返した）」を、生値だけからでも正しく区別できる
// （要件 7.4）。
//
// Preconditions: **サンプリング間隔中の真の変化量の絶対値が modulus/2
// 未満であること。** これが崩れると「短い側」の折り返し方向を取り違える
// （例えば modulus/2 を超えて一気に回ると、実際より小さい／逆方向の変化と
// 誤認識する）。この前提が本機の想定でどれだけ余裕を持つかを、他の資料を
// 丸写しせず改めて見積もっておく:
//   - エンコーダの目安分解能: 11 PPR（片相）× 減速比 約19 × 4逓倍
//     （直交エンコーダのA/B両エッジを数える方式） ≈ 836 カウント / 出力軸
//     1回転。実測校正前の目安値であり、確定値ではない（要件 7.6、A-10）。
//   - 想定される最悪回転速度: 無負荷 530 RPM ≈ 530/60 ≈ 8.83 rev/s。
//   - 上記2つを掛けると、最悪ケースのカウント変化率は
//     8.83 rev/s × 836 counts/rev ≈ 7,385 counts/s。
//   - 法を符号付き16bit相当の 65536 とすると modulus/2 = 32,768。
//     32,768 counts ÷ 7,385 counts/s ≈ 4.4 秒が、折り返し方向を取り違え
//     ずにいられる最大サンプリング間隔になる。
//   - 想定制御周期は 100〜200 Hz（5〜10 ms 間隔、OQ-22 は実測待ちだが目安
//     はこの帯）であり、4.4 秒はこれよりおよそ 3桁（440〜880倍）大きい。
//     エンコーダ読み出しが多少遅延・欠測しても、この前提が現実の運用で
//     破綻する余地はほぼ無い。
// この見積もりは modulus=65536・836 counts/rev・530 RPM を前提にした目安
// であり、法が変わればここでの数値もそのまま変わる（Risks 参照）。
//
// Postconditions: update() は前回値との差を法で最短経路へ折り返して積算
// した、単調に連続な64bit累積値を返す。正転から折り返しても逆転から
// 折り返しても、回転方向を取り違えない（要件 7.4）。
//
// Invariants: 累積値は std::int64_t で保持する。処理系に依らず同一幅で
// あり、ホストと ESP32 (xtensa) でオーバーフロー挙動が一致する（要件
// 4.4）。int64_t が飽和するのはカウント約 9.2×10^18（= 2^63 - 1）に相当し、
// 上記の最悪カウント変化率 7,385 counts/s で割ると、飽和までに要する時間は
// およそ 9.2×10^18 / 7,385 ≈ 1.25×10^15 秒 ≈ 約4,000万年である。要件 4.5
// が求める「表現範囲を超え得る箇所の明示」として、この見積もりをここに
// 記録し、境界値近傍（初期の累積値を INT64_MAX 付近に置いた状態）での
// 挙動をホストテストで固定する（オーバーフロー自体は本 Spec の運用上
// 到達しないが、"処理系依存の未定義動作にならないこと" は表現の一部として
// 検証対象にする）。
//
// Risks: `teleop-bringup` がハードウェアカウンタをウォッチポイントで
// ゼロリセットする方式を採用する場合、法の実効的な意味が変わり得る。
// modulus をコンストラクタ引数（パラメータ）にしてあるのはこのためであり、
// 本クラス自体は 65536 を固定値として埋め込まない（要件 15.6 と同じ方針）。
//
// L4 は L1（types.hpp）と標準ヘッダのみに依存する（design.md "Dependency
// Direction"）。このファイルはビルド構成マクロ・ペリフェラル固有の型・
// 現在時刻を取得する手段のいずれも参照しない。

#include <cstdint>

namespace drivetrain_control {

class WrapAccumulator {
 public:
  // modulus: ハードウェアカウンタの法（例: 符号付き16bit カウンタなら
  //          65536）。ハードウェア側の折り返し方式が変わっても対応できる
  //          よう、固定値として埋め込まずパラメータとして受け取る。
  // initial_raw: 起動時に読み出した最初の生値。
  // 事前状態: value() == 0（起動時点を原点とする）。
  WrapAccumulator(std::int32_t modulus, std::int32_t initial_raw) noexcept;

  // 新しい生値を1つ取り込み、前回値との差を法 modulus で最短経路へ
  // 折り返してから積算し、更新後の64bit累積値を返す。
  // Preconditions: 前回の update()（またはコンストラクタ／reset()）からの
  // 真の変化量の絶対値が modulus/2 未満であること（上記コメント参照）。
  std::int64_t update(std::int32_t raw_now) noexcept;

  // 直近の update()（またはコンストラクタ／reset()）で確定した累積値を
  // 返す。副作用は無い。
  std::int64_t value() const noexcept;

  // 内部状態（直近の生値・累積値）を明示的に置き換える。modulus は変えない。
  // 起動時の再同期や、境界値（累積値の表現範囲上限近傍）からの挙動を確認
  // するテストで使う。
  void reset(std::int32_t raw_now, std::int64_t accumulated) noexcept;

 private:
  std::int32_t modulus_;
  std::int32_t last_raw_;
  std::int64_t accumulated_;
};

}  // namespace drivetrain_control
