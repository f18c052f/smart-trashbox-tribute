"""検出・追跡が送出する例外階層（要件 10.4 / 10.5）。

design.md「Error Handling / Error Strategy」が定める3区分のうち、
本モジュールが表現するのは後半2つに限る。

===========================  ==========================  ============================
区分                         扱い                        例
===========================  ==========================  ============================
正常系の無効                 **値**で返す                候補ゼロ、有効 Depth 画素
（候補ゼロ・有効画素不足・   （例外にしない）            不足、寸法不一致、
寸法不一致・ゲート外）                                    ゲート外
呼び出し方・設定の誤り       例外                        設定値が不正、ROI が
                             （起動時または初回フレーム   フレーム外、未知の方式名
                             で落とす）
前提の欠落                   例外（推測して続行しない）  内因パラメータが無い、
                                                         OpenCV が無い
===========================  ==========================  ============================

したがって、「正常系の無効」に対応する例外型はここに存在しない。検出・逆投影・
追跡の実装は、無効を **値** として返すこと。例外を送出してはならない。

`TrackingError` はパッケージ由来の失敗を一括捕捉するための入口である。
そのうち `TrackingConfigError`（設定不正、要件 10.5）は `ValueError` も
継承する。`prediction_core` の `PredictionConfigError` と同じ技法であり、
本パッケージを知らない利用側が既に書いている `except ValueError` による
防御をそのまま働かせるためである。

一方、`IntrinsicsUnavailableError`（内因パラメータ欠落、要件 10.4）と
`DetectorUnavailableError`（検出手段の前提欠落）は「設定の誤り」ではなく
「前提の欠落」であり、`ValueError` は継承しない。呼び出し側の設定値自体は
妥当でも、上流や実行環境がその前提を満たしていないために続行できない、
という別種の失敗だからである。

このモジュールは L0 層であり、標準ライブラリ以外も
パッケージ内の他モジュールも import しない（design.md「Dependency Direction」）。
"""

from __future__ import annotations


class TrackingError(Exception):
    """flying_object_tracking が送出するすべての例外の基底。

    利用側はこれを捕捉することで、本パッケージ由来の失敗だけを
    まとめて扱える。検出・追跡の無効（候補ゼロ等）はこの例外では
    表現されない。
    """


class TrackingConfigError(TrackingError, ValueError):
    """設定値が不変条件を満たさない、または呼び出し方が誤っている（要件 10.5）。

    ROI がフレーム範囲外、未知の方式名など、設定そのものが成立しない
    ときに構築時点または初回フレーム受領時点で送出する。処理開始前に
    拒否することで、不正な設定のまま検出・追跡が進む事態を防ぐ。
    """


class IntrinsicsUnavailableError(TrackingError):
    """カメラの内因パラメータが得られず、3D位置の算出を行えない（要件 10.4）。

    逆投影を推測で行うと座標が全体的にずれたまま気づかれない危険がある
    ため、黙って続行せずここで明示的に失敗する。メッセージには次に何を
    確認すべきか（多くの場合は入力元 `simulated` / `recorded` の内因
    パラメータ設定）を含めること。
    """


class DetectorUnavailableError(TrackingError):
    """検出手段が前提とするライブラリ（OpenCV 等）が利用できない。

    `types` / `config` / `tracking` / `projection` は import できる状態を
    保ったまま、「検出だけが使えない」ことを正確に表現するための例外。
    """
